"""Deterministically generate TypeScript from the packaged, versioned core schemas."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SCHEMAS = ROOT.parent / "src" / "civic_data_connectors" / "schemas"
NAMES = {"result": "OperationResult", "record": "RecordEnvelope", "source": "Source",
         "bounds": "Bounds", "query": "Query", "identity": "Identity", "error": "ConnectorError",
         "capture": "Capture", "capture-bundle": "CaptureBundle"}


def ts(value):
    if "const" in value:
        return json.dumps(value["const"])
    if "enum" in value:
        return " | ".join(json.dumps(x) for x in value["enum"])
    kind = value.get("type")
    if isinstance(kind, list):
        return " | ".join(ts({**value, "type": k}) for k in kind)
    if kind == "object":
        required = value.get("required", [])
        props = [json.dumps(k) + ("" if k in required else "?") + ": " + ts(v) + ";"
                 for k, v in value.get("properties", {}).items()]
        if value.get("additionalProperties", True):
            props.append("[key: string]: unknown;")
        return "{ " + " ".join(props) + " }"
    if kind == "array":
        return "Array<" + ts(value.get("items", {})) + ">"
    return {"string": "string", "integer": "number", "number": "number",
            "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def generate():
    lines = ["// Generated by client/generate_types.py from schema 2.0.0. Do not edit.",
             "// Unknown fields remain unknown; no provider field mapping is inferred.", ""]
    for path in sorted(SCHEMAS.glob("*.schema.json")):
        key = path.name.removesuffix(".schema.json")
        name = NAMES.get(key, "".join(x.title() for x in key.split("-")))
        lines.append(f"export type {name} = {ts(json.loads(path.read_text(encoding='utf-8')))};")
    return "\n\n".join(lines) + "\n"


if __name__ == "__main__":
    (ROOT / "src" / "generated.ts").write_text(generate(), encoding="utf-8")
